#define SWDIOOUTSHIFT __builtin_ctz(SWDIOOUT_Pin)
#define SWDIOOUTMODERMASK (0x3 << (2UL*SWDIOOUTSHIFT))
#define SWDIOOUTDRIVE SWDIOOUT_GPIO_Port->MODER = ((SWDIOOUT_GPIO_Port->MODER & (~SWDIOOUTMODERMASK)) | (0x1 << (2UL*SWDIOOUTSHIFT)))
#define SWDIOOUTHIZ SWDIOOUT_GPIO_Port->MODER = (SWDIOOUT_GPIO_Port->MODER & (~SWDIOOUTMODERMASK))
#define SWCLKOUTLOW (SWCLKOUT_Pin << 16U)
#define SWCLKOUTHIGH (SWCLKOUT_Pin)
#define SWCLKOUTPULSE \
	do{ \
		SWCLKOUT_GPIO_Port->BSRR = SWCLKOUTLOW; \
		SWCLKOUT_GPIO_Port->BSRR = SWCLKOUTHIGH; \
	}while(0)
#define SWDIOOUTDATA(bitdata) ( SWDIOOUT_Pin << (((bitdata) ^ 1UL) << 4UL) )
#define SWDIOOUTWRITE(bitdata) \
	do{ \
		SWDIOOUT_GPIO_Port->BSRR = (SWCLKOUTLOW | SWDIOOUTDATA(bitdata)); \
		SWDIOOUT_GPIO_Port->BSRR = SWCLKOUTHIGH; \
	}while(0)
#define SWDIOOUTWRITESHIFT(bitdata) \
	do{ \
		SWDIOOUT_GPIO_Port->BSRR = (SWCLKOUTLOW | SWDIOOUTDATA(bitdata & 0x1UL)); \
		data = ((data) >> 1UL); \
		SWDIOOUT_GPIO_Port->BSRR = SWCLKOUTHIGH; \
	}while(0)

#define SWDIOOUTREAD(data) \
	do{ \
		SWCLKOUT_GPIO_Port->BSRR = SWCLKOUTLOW; \
		data = ( (SWDIOOUT_GPIO_Port->IDR >> (SWDIOOUTSHIFT)) & 0x1); \
		SWCLKOUT_GPIO_Port->BSRR = SWCLKOUTHIGH; \
		__NOP(); \
		__NOP(); \
		__NOP(); \
		__NOP(); \
	}while(0)

#define SWDIOOUTREAD3(data) \
	do{ \
		SWCLKOUT_GPIO_Port->BSRR = SWCLKOUTLOW; \
		data = ((((data) & 0b111) >> 1UL) | (SWDIOOUT_GPIO_Port->IDR >> (SWDIOOUTSHIFT-2UL))); \
		SWCLKOUT_GPIO_Port->BSRR = SWCLKOUTHIGH; \
		__NOP(); \
		__NOP(); \
		__NOP(); \
		__NOP(); \
	}while(0)

#define SWDIOOUTREAD32(data) \
	do{ \
		SWCLKOUT_GPIO_Port->BSRR = SWCLKOUTLOW; \
		data = (((data) >> 1UL) | (SWDIOOUT_GPIO_Port->IDR << (31UL - (SWDIOOUTSHIFT)))); \
		SWCLKOUT_GPIO_Port->BSRR = SWCLKOUTHIGH; \
		__NOP(); \
		__NOP(); \
		__NOP(); \
		__NOP(); \
	}while(0)

